import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const m = vi.hoisted(() => ({ supported: vi.fn(), consent: vi.fn(), setConsent: vi.fn(), enabled: vi.fn(), push: vi.fn(), pushPermission: vi.fn(), session: vi.fn(), rpc: vi.fn(), upsert: vi.fn(), start: vi.fn(), stop: vi.fn(), fg: vi.fn(), bg: vi.fn(), requestFg: vi.fn(), position: vi.fn() }))
const pending = vi.hoisted(() => ({ get: vi.fn(), set: vi.fn() }))
vi.mock('../lib/nearbyAlertPreference', () => ({ supportsNearbyBackgroundAlerts: m.supported, getNearbyAlertConsent: m.consent, setNearbyAlertConsent: m.setConsent, getNearbyOptOutPending: pending.get, setNearbyOptOutPending: pending.set }))
vi.mock('../lib/notificationPreference', () => ({ getNotificationsEnabled: m.enabled }))
vi.mock('./pushRegistration', () => ({ syncPushRegistration: m.push }))
vi.mock('../lib/notifications', () => ({ hasNotificationPermission: m.pushPermission }))
vi.mock('../lib/location', () => ({ startBackgroundLocationUpdates: m.start, stopBackgroundLocationUpdates: m.stop }))
vi.mock('../lib/supabase', () => ({ supabase: { auth: { getSession: m.session }, rpc: m.rpc, from: () => ({ upsert: m.upsert }) } }))
vi.mock('expo-location', () => ({ Accuracy: { Balanced: 3 }, getForegroundPermissionsAsync: m.fg, getBackgroundPermissionsAsync: m.bg, requestForegroundPermissionsAsync: m.requestFg, getCurrentPositionAsync: m.position }))
const notice = { title: 'Nearby', body: 'Location active' }
beforeEach(() => {
  vi.resetModules()
  vi.clearAllMocks()
  m.supported.mockReturnValue(true)
  m.consent.mockResolvedValue(true)
  m.setConsent.mockResolvedValue(undefined)
  pending.get.mockResolvedValue(false)
  pending.set.mockResolvedValue(undefined)
  m.enabled.mockResolvedValue(true)
  m.push.mockResolvedValue(true)
  m.pushPermission.mockResolvedValue(true)
  m.session.mockResolvedValue({ data: { session: { user: { id: 'user' } } } })
  m.rpc.mockResolvedValue({ error: null })
  m.upsert.mockResolvedValue({ error: null })
  m.start.mockResolvedValue(true)
  m.stop.mockResolvedValue(undefined)
  for (const permission of [m.fg, m.bg, m.requestFg]) permission.mockResolvedValue({ status: 'granted' })
  m.position.mockResolvedValue({ timestamp: Date.now(), coords: { latitude: 31.77, longitude: 35.21 } })
})
afterEach(() => vi.useRealTimers())

describe('nearby background alert enrollment', () => {
  it('enrolls a general account without opening any helper screen', async () => {
    const { enableNearbyAlerts } = await import('./nearbyAlerts')
    expect(await enableNearbyAlerts('user', notice)).toBe('on')
    expect(m.upsert).toHaveBeenCalledWith(expect.objectContaining({ user_id: 'user', is_available: true, latitude: 31.77, longitude: 35.21 }))
    expect(m.rpc).toHaveBeenCalledWith('set_my_notification_preferences', { p_prefs: { requests: true } })
    expect(m.setConsent.mock.invocationCallOrder[0]).toBeLessThan(m.start.mock.invocationCallOrder[0]!)
  })
  it('cannot request Android background access from an old binary or web', async () => {
    m.supported.mockReturnValue(false)
    const { enableNearbyAlerts } = await import('./nearbyAlerts')
    expect(await enableNearbyAlerts('user', notice)).toBe('off')
    expect(m.requestFg).not.toHaveBeenCalled()
    expect(m.upsert).not.toHaveBeenCalled()
  })
  it.each(['notifications', 'push', 'foreground', 'background'])('handles denied %s without claiming activation', async denied => {
    if (denied === 'notifications') m.enabled.mockResolvedValue(false)
    if (denied === 'push') m.push.mockResolvedValue(false)
    if (denied === 'foreground') m.requestFg.mockResolvedValue({ status: 'denied' })
    if (denied === 'background') m.start.mockResolvedValue(false)
    const { enableNearbyAlerts } = await import('./nearbyAlerts')
    expect(await enableNearbyAlerts('user', notice)).toBe('permission')
    expect(m.upsert).not.toHaveBeenCalled()
    expect(m.rpc).not.toHaveBeenCalled()
    if (denied === 'background') expect(m.setConsent).toHaveBeenLastCalledWith('user', false)
  })
  it('stops collecting when initial enrollment fails', async () => {
    m.upsert.mockResolvedValue({ error: new Error('offline') })
    const { enableNearbyAlerts } = await import('./nearbyAlerts')
    await expect(enableNearbyAlerts('user', notice)).rejects.toThrow('offline')
    expect(m.stop).toHaveBeenCalled()
    expect(m.setConsent).toHaveBeenLastCalledWith('user', false)
  })
  it('refreshes on app resume without prompting for permissions', async () => {
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    expect(await refreshNearbyAlerts('user', notice)).toBe('on')
    expect(m.requestFg).not.toHaveBeenCalled()
    expect(m.start).toHaveBeenCalledWith('user', notice, false)
    expect(m.upsert).toHaveBeenCalled()
  })
  it('does not collect before consent or after the user declines', async () => {
    m.consent.mockResolvedValue(false)
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    expect(await refreshNearbyAlerts('user', notice)).toBe('off')
    expect(m.start).not.toHaveBeenCalled()
    expect(m.position).not.toHaveBeenCalled()
  })
  it('stops background collection when permission is revoked', async () => {
    m.bg.mockResolvedValue({ status: 'denied' })
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    expect(await refreshNearbyAlerts('user', notice)).toBe('permission')
    expect(m.stop).toHaveBeenCalled()
    expect(m.position).not.toHaveBeenCalled()
  })
  it('disables request pushes and location updates together', async () => {
    const { disableNearbyAlerts } = await import('./nearbyAlerts')
    expect(await disableNearbyAlerts('user')).toBe('off')
    expect(m.stop).toHaveBeenCalled()
    expect(m.rpc).toHaveBeenCalledWith('set_my_notification_preferences', { p_prefs: { requests: false } })
  })
  it('keeps GPS off and retries a failed server opt-out after reconnecting', async () => {
    m.rpc.mockResolvedValueOnce({ error: new Error('offline') })
    const { disableNearbyAlerts, refreshNearbyAlerts } = await import('./nearbyAlerts')
    await expect(disableNearbyAlerts('user')).rejects.toThrow('offline')
    expect(m.stop).toHaveBeenCalled()
    expect(m.setConsent).toHaveBeenLastCalledWith('user', false)
    expect(pending.set).toHaveBeenLastCalledWith('user', true)
    m.consent.mockResolvedValue(false)
    pending.get.mockResolvedValue(true)
    expect(await refreshNearbyAlerts('user', notice)).toBe('off')
    expect(m.rpc).toHaveBeenLastCalledWith('set_my_notification_preferences', { p_prefs: { requests: false } })
    expect(pending.set).toHaveBeenLastCalledWith('user', false)
    expect(m.position).not.toHaveBeenCalled()
  })
  it('stops collecting when notification permission is revoked in phone settings', async () => {
    m.pushPermission.mockResolvedValue(false)
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    expect(await refreshNearbyAlerts('user', notice)).toBe('permission')
    expect(m.stop).toHaveBeenCalledWith('user')
    expect(m.upsert).not.toHaveBeenCalled()
  })
  it('a disable during a slow permission prompt cannot be undone by the old enable', async () => {
    let finish!: (permission: unknown) => void
    m.requestFg.mockReturnValue(new Promise(resolve => { finish = resolve }))
    const { enableNearbyAlerts, disableNearbyAlerts } = await import('./nearbyAlerts')
    const enable = enableNearbyAlerts('user', notice)
    await vi.waitFor(() => expect(m.requestFg).toHaveBeenCalled())
    const disable = disableNearbyAlerts('user')
    finish({ status: 'granted' })
    await Promise.all([enable, disable])
    expect(m.start).not.toHaveBeenCalled()
    expect(m.upsert).not.toHaveBeenCalled()
    expect(m.setConsent).toHaveBeenLastCalledWith('user', false)
  })
  it('never saves a delayed GPS result under a different account', async () => {
    let finish!: (fix: unknown) => void
    m.position.mockReturnValue(new Promise(resolve => { finish = resolve }))
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    const work = refreshNearbyAlerts('user', notice)
    await vi.waitFor(() => expect(m.position).toHaveBeenCalled())
    m.session.mockResolvedValue({ data: { session: { user: { id: 'other' } } } })
    finish({ coords: { latitude: 31.77, longitude: 35.21 } })
    await expect(work).rejects.toThrow('ACCOUNT_CHANGED')
    expect(m.upsert).not.toHaveBeenCalled()
  })
  it('times out a stalled GPS acquisition and ignores its late result', async () => {
    vi.useFakeTimers()
    let finish!: (fix: unknown) => void
    m.position.mockReturnValue(new Promise(resolve => { finish = resolve }))
    const { refreshNearbyAlerts } = await import('./nearbyAlerts')
    const checked = expect(refreshNearbyAlerts('user', notice)).rejects.toThrow('LOCATION_TIMEOUT')
    await vi.advanceTimersByTimeAsync(25_001)
    await checked
    finish({ coords: { latitude: 31.77, longitude: 35.21 } })
    await Promise.resolve()
    expect(m.upsert).not.toHaveBeenCalled()
  })
})
